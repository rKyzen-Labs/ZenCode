/**
 * Checks whether the Tauri IPC runtime bridge is present.
 * If running inside a standard browser (e.g. Chrome during frontend testing),
 * this returns false and the mock adapter handles IPC requests gracefully.
 */
export function hasTauriBridge(): boolean {
  if (typeof window === 'undefined') return false;
  const w = window as any;
  return Boolean(
    (w.__TAURI_INTERNALS__ && typeof w.__TAURI_INTERNALS__.invoke === 'function') ||
    (w.__TAURI__?.core && typeof w.__TAURI__.core.invoke === 'function')
  );
}

